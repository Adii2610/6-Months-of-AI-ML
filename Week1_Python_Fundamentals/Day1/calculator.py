a = int(input("Enter your first Number: "))
b = int(input("Enter your second Number: "))
operator = input("Choose your operator (+,-,*,/): ")

if operator == "+":
    c = a + b
    print(c)
elif operator == "-":
    c = a - b 
    print(c)
elif operator == "*":
    c = a * b
    print(c)
elif operator == "/":
    c = a / b
    print(c)

